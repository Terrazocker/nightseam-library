"""Bake the project-owned core/ snapshot to local content-hashed URLs.

The core is authored once in core/*.js and copied to
  static/js/core/<hash>/      (bundled into the catalog exe via static/)
plus a stable entry stub at static/js/core.js whose
explicit export list is derived from core/index.js. A core change therefore
produces new URLs and increments the manifest token automatically. The guard
scripts/check_core.py checks source/bake byte identity, stub hash and retention.

Byte identity is line-ending normalized, so a CRLF checkout and an LF checkout
hash the same.

Usage: python scripts/build_core.py
"""

from __future__ import annotations

import hashlib
import argparse
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CORE = ROOT / "core"
MANIFEST = CORE / "core.manifest.json"
STATIC_JS = ROOT / "static" / "js"
STUB_NAME = "core.js"


def normalize(data: bytes) -> bytes:
    """Line-ending normalization for hashing and baking (CRLF -> LF)."""
    return data.replace(b"\r\n", b"\n")


def core_root(root: Path | None = None) -> Path:
    return CORE if root is None else Path(root)


def core_files(root: Path | None = None) -> list[Path]:
    base = core_root(root)
    return sorted(p for p in base.rglob("*.js") if p.is_file())


def tree_hash(root: Path | None = None) -> tuple[str, dict[str, str]]:
    """Stable 16-hex tree hash + per-file sha256 (line-ending normalized)."""
    base = core_root(root)
    digest = hashlib.sha256()
    files: dict[str, str] = {}
    for p in core_files(base):
        rel = p.relative_to(base).as_posix()
        one = hashlib.sha256(normalize(p.read_bytes())).hexdigest()
        files[rel] = one
        digest.update(rel.encode("utf-8") + b"\0" + one.encode("ascii") + b"\n")
    return digest.hexdigest()[:16], files


def export_names(index_text: str) -> list[str]:
    """Explicit export list from every `export { ... }` block in core/index.js
    (the stub mirrors it; order preserved, duplicates dropped)."""
    names: list[str] = []
    for match in re.finditer(r"export\s*\{([^}]+)\}", index_text):
        for part in match.group(1).split(","):
            piece = part.strip().split(" as ")
            if piece and piece[-1].strip() and piece[-1].strip() not in names:
                names.append(piece[-1].strip())
    return names


def stub_text(hash_: str, names: list[str]) -> str:
    return ("// GENERATED by scripts/build_core.py - do not edit.\n"
            f"export {{ {', '.join(names)} }} from './core/{hash_}/index.js';\n")


def next_previous(old_hash: str | None, old_previous: str | None,
                  new_hash: str) -> str | None:
    """The retained N-1 hash after a bake (XL-02).

    A CHANGED tree makes the old hash the new N-1. An IDEMPOTENT re-bake (same
    tree) must CARRY the recorded previous forward instead of forgetting it -
    otherwise the prune step would delete a directory that a visitor holding a
    cached older `core.js` stub may still need."""
    if old_hash == new_hash:
        return old_previous if old_previous != new_hash else None
    return old_hash


def previous_for_bake(old_hash: str | None, old_previous: str | None,
                      new_hash: str, *, retire_model_bearing_previous: bool = False
                      ) -> str | None:
    """Select N-1, with the narrow one-time retirement escape hatch.

    The retirement flag is used only when a model-bearing core module is
    removed. Ordinary builds keep the documented current + N-1 policy.
    """
    if retire_model_bearing_previous:
        return None
    return next_previous(old_hash, old_previous, new_hash)


def retention_keep(hash_: str, previous: str | None) -> set[str]:
    """The baked-core RETENTION POLICY, in one place (XL-02, 0.6.24 review).

    Keep the CURRENT content-hashed dir plus the immediately previous one (N-1) so
    a visitor holding a cached old `core.js` stub still resolves its tree; anything
    older is stale and goes at the next re-bake. `check_core.py` enforces exactly
    this set, so the documented policy cannot drift from the guard again."""
    keep = {hash_}
    if previous and previous != hash_:
        keep.add(previous)
    return keep


def prune_baked_dirs(dest_root: Path, keep: set[str]) -> list[str]:
    """Remove baked hash dirs that are not in `keep`; returns the removed names."""
    removed: list[str] = []
    if dest_root.is_dir():
        for child in dest_root.iterdir():
            if child.is_dir() and child.name not in keep:
                shutil.rmtree(child)
                removed.append(child.name)
    return removed


def prior_manifest_values(manifest: object) -> tuple[str, int, str | None]:
    """Validate retention anchors before any existing bake can be changed."""
    if not isinstance(manifest, dict):
        raise ValueError("manifest must be an object")
    old_hash = manifest.get("hash")
    if (not isinstance(old_hash, str)
            or re.fullmatch(r"[0-9a-f]{16}", old_hash) is None):
        raise ValueError("manifest hash must be 16 lowercase hexadecimal characters")
    token = manifest.get("token")
    # bool is an int subclass; coercing strings/floats also loses provenance.
    if type(token) is not int or token <= 0:
        raise ValueError("manifest token must be a positive integer")
    previous = manifest.get("previous")
    if previous is not None and (
            not isinstance(previous, str)
            or re.fullmatch(r"[0-9a-f]{16}", previous) is None):
        raise ValueError("manifest previous must be null or a 16-character "
                         "lowercase hexadecimal hash")
    return old_hash, token, previous


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--retire-model-bearing-previous", action="store_true",
        help="one-time feature retirement: drop the old N-1 bake after its source is removed")
    args = parser.parse_args()
    if not CORE.is_dir():
        print("build_core: core/ is missing")
        return 1
    if args.retire_model_bearing_previous and (CORE / "skybrightness.js").exists():
        print("build_core: cannot retire the previous model bake while its source remains")
        return 1
    hash_, files = tree_hash()
    token = 1
    previous = None
    old_hash = None
    if MANIFEST.is_file():
        # F-20: a PRESENT but corrupt manifest must refuse the bake - silently
        # treating it as fresh reset the token to 1 and dropped the previous
        # link, so the retention policy lost its history anchor.
        try:
            old = json.loads(MANIFEST.read_text(encoding="utf-8"))
            old_hash, token, previous = prior_manifest_values(old)
        except (OSError, ValueError) as exc:
            print(f"build_core: refusing to bake over a corrupt manifest "
                  f"({exc}) - restore or delete core/core.manifest.json "
                  f"deliberately, then retry")
            return 1
    previous = previous_for_bake(
        old_hash, previous, hash_,
        retire_model_bearing_previous=args.retire_model_bearing_previous)
    if old_hash and old_hash != hash_:
        token += 1
    names = export_names((CORE / "index.js").read_text(encoding="utf-8"))
    if not names:
        print("build_core: core/index.js has no explicit export list")
        return 1
    keep = retention_keep(hash_, previous)
    for dest_root in (STATIC_JS / "core",):
        stale = prune_baked_dirs(dest_root, keep)
        if stale:
            print("build_core: pruned stale baked dir(s): "
                  + ", ".join(sorted(stale)))
        dest = dest_root / hash_
        for p in core_files():
            target = dest / p.relative_to(CORE)
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(normalize(p.read_bytes()))
    (STATIC_JS / STUB_NAME).write_text(stub_text(hash_, names),
                                       encoding="utf-8", newline="\n")
    MANIFEST.write_text(
        json.dumps({"hash": hash_, "token": token, "previous": previous,
                    "files": files}, indent=2) + "\n",
        encoding="utf-8", newline="\n")
    print(f"build_core: hash={hash_} token={token} files={len(files)} "
          f"-> static/js/core/{hash_}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
