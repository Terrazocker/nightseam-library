def _epoch(iso):
    if iso is None:
        return None
    return datetime.fromisoformat(iso.replace("Z", "+00:00"))


def test_twilight_matches_the_oracle(fixtures, got):
    exp, res = _section(got, fixtures, "twilight")
    tol = fixtures["manifest"]["tolerances"]["twilight_s"]
    for c, have in zip(exp, res):
        assert have["level"] == c["level"], (c["site"], c["date"], have, c["level"])
        for key in ("sunset", "sunrise", "dusk", "dawn"):
            want = _epoch(c[key])
            if want is None:
                assert have[key] is None, (c["site"], c["date"], key, have[key])
                continue
            have_dt = _epoch(have[key])
            delta = abs((want - have_dt).total_seconds())
            assert delta <= tol, (c["site"], c["date"], key, delta, have[key], c[key])
