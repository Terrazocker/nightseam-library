"""Class P fixtures: core/ against the frozen Python oracle (Phase 2).

tests/fixtures/core_fixtures.json is FROZEN: it was generated by the retired
`python scripts/gen_core_fixtures.py` (Phase C removed the Python oracle, so it
can no longer be regenerated) and is now one of the committed goldens. The node
runner evaluates core with the SAME inputs; this test compares per concept with
the fixture manifest's tolerances. Sections whose core functions are not
extracted yet are skipped, so the harness can land before concepts 6-8.
"""

import json
import shutil
import subprocess
from datetime import datetime, timezone
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
FIXTURES = ROOT / "tests" / "fixtures" / "core_fixtures.json"
RUNNER = ROOT / "tests" / "js" / "core_fixtures.mjs"


def _run(core_dir: Path | None = None) -> dict:
    node = shutil.which("node")
    if not node:
        pytest.fail("node is not installed - core fixtures cannot run")
    argv = [node, str(RUNNER), str(FIXTURES)]
    if core_dir is not None:
        argv.append(str(core_dir))
    try:
        proc = subprocess.run(argv, capture_output=True, text=True,
                              encoding="utf-8", timeout=180, cwd=str(ROOT))
    except OSError as exc:          # sandboxed environments deny pipe creation
        pytest.fail(f"cannot spawn node here: {exc}")
    assert proc.returncode == 0, f"fixture runner failed:\n{proc.stderr[-2000:]}"
    return json.loads(proc.stdout)


@pytest.fixture(scope="module")
def fixtures():
    return json.loads(FIXTURES.read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def got():
    return _run()


def _close(a, b, tol):
    if a is None or b is None:
        return a is None and b is None
    return abs(a - b) <= tol


def _section(got, fixtures, name):
    """TS7 / TO-10 (0.6.24 review): a section the harness did not produce is a
    FAILURE, not a skip.

    The gating existed while the harness landed before Phase 2 ("concept not
    extracted yet"); the core is complete now, so a missing section can only mean
    a renamed, removed or no-longer-function export - and a silently skipped
    fixture comparison is exactly what this file exists to prevent."""
    if name not in got:
        gone = (got.get("missing") or {}).get(name) or []
        pytest.fail(
            f"core/{name} fixtures were not produced - missing export(s): "
            f"{', '.join(gone) or 'unknown'}. A rename/removal must be an explicit "
            "decision, not a silent skip.")
    return fixtures[name], got[name]


def test_a_missing_section_fails_instead_of_skipping():
    """TO-10 (TS7): the harness reports WHICH core export vanished, and the Python
    side must FAIL - a silently skipped fixture comparison is exactly what this
    file exists to prevent.

    Written with an explicit `except BaseException` so a reverted `pytest.skip`
    FAILS this pin instead of skipping it (proved by mutation)."""
    try:
        _section({"missing": {"jd": ["julianDay"]}}, {"jd": []}, "jd")
    except pytest.fail.Exception as exc:               # the exception itself
        assert "julianDay" in str(exc), str(exc)
    except BaseException as exc:                       # Skipped included
        pytest.fail(f"a missing section must FAIL, not {type(exc).__name__}: {exc}")
    else:
        pytest.fail("a missing section must FAIL")


def test_jd_matches_the_oracle(fixtures, got):
    exp, res = _section(got, fixtures, "jd")
    tol = fixtures["manifest"]["tolerances"]["jd"]
    for c, have in zip(exp, res):
        assert _close(c["jd"], have, tol), (c["iso"], c["jd"], have)


